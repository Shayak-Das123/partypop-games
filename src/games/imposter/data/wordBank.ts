function transformRaw(raw: [string, string, string, string][], category: WordItem['category']): WordItem[] {
  return raw.map(([word, undercoverWord, oneWord, twoWord], index) => ({
    id: `${category}_${index + 1}`,
    category,
    word: word.trim(),
    undercoverWord: undercoverWord.trim(),
    hints: {
      oneWord: oneWord.trim(),
      twoWord: twoWord.trim(),
    },
  }));
}

