import { getNonRepeatingItem } from '../../../services/sessionDeckManager';

export function getRandomWord(categories: WordItem['category'][]): WordItem {
  const activeCats = categories.length > 0 ? categories : (['everyday_objects'] as WordItem['category'][]);
  const pool = activeCats.flatMap(cat => ALL_WORDS_BY_CATEGORY[cat]);
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}

export function getNonRepeatingWord(sessionId: string, categories: WordItem['category'][]): WordItem {
  const activeCats = categories.length > 0 ? categories : (['everyday_objects'] as WordItem['category'][]);
  const pool = activeCats.flatMap(cat => ALL_WORDS_BY_CATEGORY[cat]);
  const deckKey = `imposter_${[...activeCats].sort().join('_')}`;
  return getNonRepeatingItem(sessionId, deckKey, pool, item => item.id);
}

