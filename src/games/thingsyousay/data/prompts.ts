import { getNonRepeatingItem } from '../../../services/sessionDeckManager';

/**
 * Get random prompt according to selected mode (never repeats in same session!)
 */
export function getNonRepeatingPromptByMode(sessionId: string, mode: ThingsYouSayMode = 'classic'): string {
  let pool = CLASSIC_EASY_PROMPTS;
  if (mode === 'in_bed') {
    pool = IN_BED_PROMPTS;
  } else if (mode === 'mixed') {
    pool = [...CLASSIC_EASY_PROMPTS, ...IN_BED_PROMPTS];
  }
  return getNonRepeatingItem(sessionId || 'global', `thingsyousay_${mode}`, pool);
}

/**
 * Get random prompt according to selected mode
 */
export function getRandomPromptByMode(mode: ThingsYouSayMode = 'classic'): string {
  return getNonRepeatingPromptByMode('global', mode);
}

// Backwards-compatible export
export const THINGS_YOU_CAN_SAY_PROMPTS = CLASSIC_EASY_PROMPTS;

export function getRandomPrompt(): string {
  return getRandomPromptByMode('classic');
}

