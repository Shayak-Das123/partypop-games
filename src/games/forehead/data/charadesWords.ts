import { getNonRepeatingItem } from '../../../services/sessionDeckManager';

export function getRandomWordFromDeck(deckIds: string[]): string {
  const activeDecks = CHARADES_DECKS.filter(d => deckIds.includes(d.id));
  const pool = activeDecks.length > 0 ? activeDecks.flatMap(d => d.words) : CHARADES_DECKS[0].words;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getNonRepeatingWordFromDeck(sessionId: string, deckIds: string[]): string {
  const activeDecks = CHARADES_DECKS.filter(d => deckIds.includes(d.id));
  const pool = activeDecks.length > 0 ? activeDecks.flatMap(d => d.words) : CHARADES_DECKS[0].words;
  const deckKey = `forehead_${[...deckIds].sort().join('_')}`;
  return getNonRepeatingItem(sessionId, deckKey, pool, w => w);
}

